use std::collections::VecDeque;
use std::io::{self, BufRead, Read};

use super::protocol::crc;
use super::*;

struct Script {
    replies: VecDeque<Vec<u8>>,
    input: Vec<u8>,
    offset: usize,
    chunk: usize,
    end: Option<io::ErrorKind>,
    send_error: Option<io::ErrorKind>,
    sent: Vec<Vec<u8>>,
}
impl Script {
    fn new(replies: Vec<Vec<u8>>) -> Self {
        Self {
            replies: replies.into(),
            input: vec![],
            offset: 0,
            chunk: usize::MAX,
            end: None,
            send_error: None,
            sent: vec![],
        }
    }
}
impl Read for Script {
    fn read(&mut self, buffer: &mut [u8]) -> io::Result<usize> {
        let available = self.fill_buf()?;
        let count = buffer.len().min(available.len());
        buffer[..count].copy_from_slice(&available[..count]);
        self.consume(count);
        Ok(count)
    }
}
impl BufRead for Script {
    fn fill_buf(&mut self) -> io::Result<&[u8]> {
        if self.offset == self.input.len()
            && let Some(error) = self.end
        {
            return Err(error.into());
        }
        Ok(&self.input[self.offset..self.offset.saturating_add(self.chunk).min(self.input.len())])
    }
    fn consume(&mut self, count: usize) {
        self.offset += count;
    }
}
impl DeviceIo for Script {
    fn send(&mut self, bytes: &[u8]) -> io::Result<()> {
        assert_eq!(self.offset, self.input.len(), "response tail reused");
        self.sent.push(bytes.to_vec());
        if let Some(error) = self.send_error {
            return Err(error.into());
        }
        self.input = self
            .replies
            .pop_front()
            .expect("unexpected transaction / retry");
        self.offset = 0;
        Ok(())
    }
}
fn driver(scale: f64, writable: bool) -> Metakon {
    Metakon::from_options(&toml::from_str(&format!(
        "address=15\nchannel=0\nprocess_value_scale={scale:?}\nprocess_value_unit='degC'\nwrite_enabled={writable}"
    )).unwrap()).unwrap()
}
fn checked(mut bytes: Vec<u8>) -> Vec<u8> {
    bytes.push(crc(&bytes));
    bytes
}
fn reply(register: u8, flags: u8, data: &[u8]) -> Vec<u8> {
    let mut bytes = vec![15, 0, register, 0, flags];
    bytes.extend_from_slice(data);
    checked(bytes)
}

#[test]
fn crc_and_frames_match_independent_published_and_donor_vectors() {
    // Manufacturer table 11; literal multi-byte frames from com_port_reader,
    // not expectations generated by the codec under test. See driver docs.
    for (input, expected) in [
        (0x00, 0x35),
        (0x01, 0x6b),
        (0x02, 0x89),
        (0x20, 0x16),
        (0x80, 0xb9),
        (0xc0, 0xff),
        (0xff, 0),
    ] {
        assert_eq!(crc(&[input]), expected);
    }
    assert_eq!(read_request(1, 0, 1), [1, 0, 1, 0, 0xa0]);
    assert_eq!(read_request(2, 0, 1), [2, 0, 1, 0, 0x28]);
    assert_eq!(
        write_request(15, 0, 2, I16, &Value::Integer(1234)),
        [15, 0, 2, 1, 4, 0xd2, 4, 0x7e]
    );
    assert_eq!(
        write_request(15, 0, 6, I8, &Value::Integer(-25)),
        [15, 0, 6, 1, 2, 0xe7, 0x2b]
    );
    validate_reply(&[15, 0, 2, 1, 0xbe], &[15, 0, 2, 1]).unwrap();
    let mut d = Metakon::from_options(
        &toml::from_str("address=1\nchannel=0\nprocess_value_scale=0.1").unwrap(),
    )
    .unwrap();
    assert_eq!(
        d.read(
            "measurement",
            &mut Script::new(vec![vec![1, 0, 1, 0, 0x44, 0xd2, 4, 0xf1]])
        )
        .unwrap(),
        Value::Float(123.4)
    );
    let mut d = Metakon::from_options(
        &toml::from_str("address=2\nchannel=1\nprocess_value_scale=1.0").unwrap(),
    )
    .unwrap();
    assert_eq!(
        d.read(
            "measurement",
            &mut Script::new(vec![vec![2, 1, 1, 0, 0x44, 0x85, 0xff, 0xcc]])
        )
        .unwrap(),
        Value::Integer(-123)
    );
}

#[test]
fn decodes_every_wire_type_and_boolean_ff_not_01() {
    for (wire, bytes, expected) in [
        (Bool, vec![0], Value::Boolean(false)),
        (Bool, vec![255], Value::Boolean(true)),
        (U8, vec![255], Value::Integer(255)),
        (I8, vec![0x80], Value::Integer(-128)),
        (U16, vec![0xff, 0xff], Value::Integer(65535)),
        (I16, vec![0x00, 0x80], Value::Integer(-32768)),
    ] {
        assert_eq!(wire.decode(&bytes).unwrap(), expected);
        assert!(wire.decode(&[]).is_err());
        assert!(wire.decode(&[0, 0, 0]).is_err());
    }
    for byte in [1, 2, 0x7f, 0xfe] {
        assert_eq!(
            Bool.decode(&[byte]).unwrap_err().port_state,
            PortState::Desynchronized
        );
    }
}

#[test]
fn catalog_covers_all_registers_ranges_units_and_interlock() {
    let d = driver(1.0, true);
    let descriptions = d.parameters();
    let expected = [
        ("channel_type", 0, 255, "", false),
        ("measurement", -999, 9999, "degC", false),
        ("setpoint", -999, 9999, "degC", true),
        ("proportional_band", 1, 9999, "degC", true),
        ("integral_time", 1, 30000, "s", true),
        ("derivative_time", 0, 255, "s", true),
        ("output_power", -100, 100, "%", true),
        ("pwm_positive", 0, 1, "", false),
        ("pwm_negative", 0, 1, "", false),
        ("upper_setpoint", -999, 9999, "degC", true),
        ("upper_hysteresis", 0, 255, "degC", true),
        ("upper_output", 0, 1, "", true),
        ("lower_setpoint", -999, 9999, "degC", true),
        ("lower_hysteresis", 0, 255, "degC", true),
        ("lower_output", 0, 1, "", true),
    ];
    assert_eq!(descriptions.len(), 15);
    for (index, (description, (key, min, max, unit, writable))) in
        descriptions.iter().zip(expected).enumerate()
    {
        assert_eq!(description.id, key);
        assert_eq!(REGISTERS[index].address, index as u8);
        assert_eq!(description.unit, unit);
        assert_eq!(description.writable, writable);
        if matches!(index, 7 | 8 | 11 | 14) {
            assert!(matches!(description.spec, Spec::Boolean));
        } else {
            assert!(matches!(description.spec,Spec::Integer{min:a,max:b} if a==min && b==max));
        }
        assert_eq!(
            description.default_poll_period.is_some(),
            matches!(index, 1 | 6)
        );
    }
    assert!(driver(1.0, false).parameters().iter().all(|p| !p.writable));
}

#[test]
fn every_register_is_read_and_written_with_its_own_wire_address_and_type() {
    let mut d = driver(1.0, true);
    for (address, flags, data, value) in [
        (0, 0x41, vec![3], Value::Integer(3)),
        (1, 0x44, vec![0x85, 0xff], Value::Integer(-123)),
        (2, 0xc4, vec![0x85, 0xff], Value::Integer(-123)),
        (3, 0xc3, vec![0x0f, 0x27], Value::Integer(9999)),
        (4, 0xc3, vec![0x30, 0x75], Value::Integer(30000)),
        (5, 0xc1, vec![255], Value::Integer(255)),
        (6, 0xc2, vec![0xe7], Value::Integer(-25)),
        (7, 0x40, vec![255], Value::Boolean(true)),
        (8, 0x40, vec![0], Value::Boolean(false)),
        (9, 0xc4, vec![10, 0], Value::Integer(10)),
        (10, 0xc1, vec![7], Value::Integer(7)),
        (11, 0xc0, vec![255], Value::Boolean(true)),
        (12, 0xc4, vec![20, 0], Value::Integer(20)),
        (13, 0xc1, vec![5], Value::Integer(5)),
        (14, 0xc0, vec![0], Value::Boolean(false)),
    ] {
        let key = REGISTERS[address as usize].key;
        let response = reply(address, flags, &data);
        let mut io = Script::new(vec![response.clone()]);
        io.chunk = 1; // fragmentation must not be mistaken for a truncated frame
        assert_eq!(d.read(key, &mut io).unwrap(), value);
        assert_eq!(io.sent, [read_request(15, 0, address)]);
        if flags & 0x80 != 0 {
            let mut io = Script::new(vec![checked(vec![15, 0, address, 1]), response]);
            d.write(key, &value, &mut io).unwrap();
            let mut expected = vec![15, 0, address, 1, flags & 0x0f];
            expected.extend(data);
            assert_eq!(
                io.sent,
                [checked(expected), read_request(15, 0, address).to_vec()]
            );
        }
    }
}

#[test]
fn rejects_wrong_read_identity_type_flags_crc_and_length() {
    let good = reply(1, 0x44, &[0xd2, 4]);
    for index in 0..5 {
        let mut bad = good[..good.len() - 1].to_vec();
        bad[index] ^= 1;
        let mut io = Script::new(vec![checked(bad)]);
        assert_eq!(
            driver(1.0, false)
                .read("measurement", &mut io)
                .unwrap_err()
                .port_state,
            PortState::Desynchronized
        );
        assert_eq!(io.sent.len(), 1);
    }
    for flags in [0x04, 0x54, 0x64, 0xc4] {
        assert_eq!(
            driver(1.0, false)
                .read(
                    "measurement",
                    &mut Script::new(vec![reply(1, flags, &[0, 0])])
                )
                .unwrap_err()
                .port_state,
            PortState::Desynchronized
        );
    }
    let mut bad = good.clone();
    *bad.last_mut().unwrap() ^= 1;
    assert_eq!(
        driver(1.0, false)
            .read("measurement", &mut Script::new(vec![bad]))
            .unwrap_err()
            .port_state,
        PortState::Desynchronized
    );
    let mut long = good.clone();
    long.push(0);
    assert_eq!(
        driver(1.0, false)
            .read("measurement", &mut Script::new(vec![long]))
            .unwrap_err()
            .port_state,
        PortState::Desynchronized
    );
    for length in 0..good.len() {
        let mut io = Script::new(vec![good[..length].to_vec()]);
        io.end = Some(io::ErrorKind::TimedOut);
        assert_eq!(
            driver(1.0, false)
                .read("measurement", &mut io)
                .unwrap_err()
                .port_state,
            PortState::Desynchronized
        );
        assert_eq!(io.sent.len(), 1);
    }
}

#[test]
fn sensor_fault_and_complete_out_of_range_reply_are_synchronized_errors() {
    for (raw, message) in [
        (-32768i16, "sensor fault"),
        (-1000, "outside register range"),
        (10000, "outside register range"),
    ] {
        let mut io = Script::new(vec![
            reply(1, 0x44, &raw.to_le_bytes()),
            reply(6, 0xc2, &[42]),
        ]);
        let mut d = driver(0.1, false);
        let error = d.read("measurement", &mut io).unwrap_err();
        assert_eq!(error.port_state, PortState::Synchronized);
        assert!(error.message.contains(message));
        assert_eq!(d.read("output_power", &mut io).unwrap(), Value::Integer(42));
    }
}

#[test]
fn physical_scaling_is_strict_and_preserves_integer_and_boolean_types() {
    let mut d = driver(0.1, true);
    for index in [1, 2, 3, 9, 10, 12, 13] {
        assert!(matches!(d.parameters()[index].spec, Spec::Float { .. }));
    }
    let mut io = Script::new(vec![reply(10, 0xc1, &[7])]);
    assert_eq!(
        d.read("upper_hysteresis", &mut io).unwrap(),
        Value::Float(7.0 * 0.1)
    );
    let mut io = Script::new(vec![checked(vec![15, 0, 2, 1]), reply(2, 0xc4, &[3, 0])]);
    d.write("setpoint", &Value::Float(0.3), &mut io).unwrap();
    assert_eq!(&io.sent[0][5..7], &[3, 0]);
    for (key, value) in [
        ("setpoint", Value::Integer(3)),
        ("setpoint", Value::Float(0.35)),
        ("setpoint", Value::Float(1000.0)),
        ("setpoint", Value::Float(f64::NAN)),
        ("setpoint", Value::Float(f64::INFINITY)),
        ("integral_time", Value::Float(60.0)),
        ("output_power", Value::Float(20.0)),
        ("upper_output", Value::Integer(1)),
        ("upper_output", Value::Float(1.0)),
        ("output_power", Value::Boolean(true)),
        ("output_power", Value::Integer(101)),
        ("output_power", Value::Integer(-101)),
        ("integral_time", Value::Integer(0)),
        ("integral_time", Value::Integer(30001)),
        ("derivative_time", Value::Integer(256)),
    ] {
        let mut io = Script::new(vec![]);
        assert_eq!(
            d.write(key, &value, &mut io).unwrap_err().port_state,
            PortState::Synchronized
        );
        assert!(io.sent.is_empty());
    }
}

#[test]
fn readonly_and_unknown_parameters_never_send_bytes() {
    for enabled in [false, true] {
        let mut d = driver(1.0, enabled);
        let mut io = Script::new(vec![]);
        for key in [
            "channel_type",
            "measurement",
            "pwm_positive",
            "pwm_negative",
            "missing",
        ] {
            assert!(d.write(key, &Value::Integer(0), &mut io).is_err());
        }
        if !enabled {
            for register in REGISTERS {
                assert!(d.write(register.key, &Value::Integer(1), &mut io).is_err());
            }
        }
        assert!(d.read("missing", &mut io).is_err());
        assert!(io.sent.is_empty());
    }
    let d = Metakon::from_options(
        &toml::from_str("address=0\nchannel=2\nprocess_value_scale=1.0").unwrap(),
    )
    .unwrap();
    assert!(d.parameters().iter().all(|p| !p.writable));
}

#[test]
fn write_ack_must_be_exact_and_correlated_before_readback() {
    let good = [15, 0, 2, 1, 0xbe];
    let mut cases = vec![
        vec![],
        good[..4].to_vec(),
        vec![15, 0, 2, 1, 0],
        vec![15, 0, 2, 1, 0xbe, 0],
    ];
    for index in 0..4 {
        let mut bad = good[..4].to_vec();
        bad[index] ^= 1;
        cases.push(checked(bad));
    }
    for bad in cases {
        let mut io = Script::new(vec![bad]);
        io.end = Some(io::ErrorKind::TimedOut);
        assert_eq!(
            driver(1.0, true)
                .write("setpoint", &Value::Integer(1234), &mut io)
                .unwrap_err()
                .port_state,
            PortState::Desynchronized
        );
        assert_eq!(io.sent.len(), 1);
    }
}

#[test]
fn readback_failure_never_repeats_the_write_or_reports_success() {
    for (response, state) in [
        (reply(2, 0xc4, &[1, 0]), PortState::Synchronized),
        (vec![], PortState::Desynchronized),
    ] {
        let mut io = Script::new(vec![vec![15, 0, 2, 1, 0xbe], response]);
        io.end = Some(io::ErrorKind::TimedOut);
        let error = driver(1.0, true)
            .write("setpoint", &Value::Integer(1234), &mut io)
            .unwrap_err();
        assert_eq!(error.port_state, state);
        assert_eq!(io.sent.len(), 2);
        assert_eq!(io.sent.iter().filter(|f| f[3] == 1).count(), 1);
    }
}

#[test]
fn distinguishes_disconnect_from_timeout_on_read_send_and_write() {
    for (kind, state) in [
        (io::ErrorKind::TimedOut, PortState::Desynchronized),
        (io::ErrorKind::WouldBlock, PortState::Desynchronized),
        (io::ErrorKind::BrokenPipe, PortState::Disconnected),
        (io::ErrorKind::UnexpectedEof, PortState::Disconnected),
    ] {
        for send_error in [false, true] {
            for write in [false, true] {
                let mut io = Script::new(vec![vec![]]);
                if send_error {
                    io.send_error = Some(kind);
                } else {
                    io.end = Some(kind);
                }
                let mut d = driver(1.0, true);
                let error = if write {
                    d.write("setpoint", &Value::Integer(1), &mut io)
                        .unwrap_err()
                } else {
                    d.read("measurement", &mut io).unwrap_err()
                };
                assert_eq!(error.port_state, state);
                assert_eq!(io.sent.len(), 1);
            }
        }
    }
    let error = driver(1.0, false)
        .read("measurement", &mut Script::new(vec![vec![15]]))
        .unwrap_err();
    assert_eq!(error.port_state, PortState::Disconnected);
}

#[test]
fn options_reject_unknown_missing_wrong_types_ranges_and_nonfinite_scale() {
    let valid = "address=1\nchannel=0\nprocess_value_scale=0.1\n";
    for bad in [
        "",
        "address=1\nchannel=0",
        "address=1\nprocess_value_scale=1.0",
        "channel=0\nprocess_value_scale=1.0",
    ] {
        assert!(Metakon::from_options(&toml::from_str(bad).unwrap()).is_err());
    }
    for (key, values) in [
        ("address", vec!["-1", "256", "1.0", "true", "'1'"]),
        ("channel", vec!["-1", "3", "256", "0.0", "false"]),
        (
            "process_value_scale",
            vec!["0.0", "-0.1", "nan", "inf", "1e308", "'0.1'", "true"],
        ),
        ("write_enabled", vec!["1", "'false'"]),
        ("process_value_unit", vec!["1", "true"]),
        ("unknown", vec!["1"]),
    ] {
        for value in values {
            let mut options: toml::Table = toml::from_str(valid).unwrap();
            let other: toml::Table = toml::from_str(&format!("{key}={value}")).unwrap();
            options.extend(other);
            assert!(
                Metakon::from_options(&options).is_err(),
                "accepted {key}={value}"
            );
        }
    }
    for address in [0, 255] {
        assert!(
            Metakon::from_options(
                &toml::from_str(&format!(
                    "address={address}\nchannel=2\nprocess_value_scale=1.0"
                ))
                .unwrap()
            )
            .is_ok()
        );
    }
}
